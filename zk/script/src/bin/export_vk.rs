//! Writes SP1's Groth16 verifying key as big-endian alt_bn128 points for the Solana program
//! (oracle/programs/pct_oracle/src/sp1_vk.rs), so the program never decompresses points.
use ark_serialize::CanonicalSerialize;
use sha2::{Digest, Sha256};
use sp1_verifier::{load_ark_groth16_verifying_key_from_bytes, VK_ROOT_BYTES};

const VK: &[u8] = include_bytes!("../../../fixtures/sp1-v6-groth16_vk.bin");

/// Arkworks writes each field element little-endian; alt_bn128 wants big-endian, and for G2 the
/// (c1, c0) order, which reversing each 64-byte coordinate gives.
fn be<const CHUNK: usize>(p: &impl CanonicalSerialize) -> Vec<u8> {
    let mut buf = Vec::new();
    p.serialize_uncompressed(&mut buf).unwrap();
    buf.chunks(CHUNK).flat_map(|c| c.iter().rev().copied()).collect()
}

fn arr(b: &[u8]) -> String {
    format!("[{}]", b.iter().map(|x| format!("0x{x:02x}")).collect::<Vec<_>>().join(", "))
}

fn main() {
    let vk = load_ark_groth16_verifying_key_from_bytes(VK).unwrap();
    let prefix = &Sha256::digest(VK)[..4];
    let mut out = String::from("//! SP1 v6 Groth16 verifying key (circuit v6.1.0), generated by `cargo run --bin export_vk` in zk/.\n//! Do not edit by hand.\n\n");
    out += &format!("pub const VK_PREFIX: [u8; 4] = {};\n", arr(prefix));
    out += &format!("pub const VK_ROOT: [u8; 32] = {};\n", arr(&VK_ROOT_BYTES[..]));
    out += &format!("pub const ALPHA_G1: [u8; 64] = {};\n", arr(&be::<32>(&vk.alpha_g1)));
    out += &format!("pub const BETA_G2: [u8; 128] = {};\n", arr(&be::<64>(&vk.beta_g2)));
    out += &format!("pub const GAMMA_G2: [u8; 128] = {};\n", arr(&be::<64>(&vk.gamma_g2)));
    out += &format!("pub const DELTA_G2: [u8; 128] = {};\n", arr(&be::<64>(&vk.delta_g2)));
    out += &format!("pub const IC: [[u8; 64]; {}] = [\n", vk.gamma_abc_g1.len());
    for p in &vk.gamma_abc_g1 {
        out += &format!("    {},\n", arr(&be::<32>(p)));
    }
    out += "];\n";
    print!("{out}");
}
