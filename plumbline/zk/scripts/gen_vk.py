"""Writes the RISC Zero Groth16 verifying key + control ids as Rust consts (big-endian, EIP-197 G2
order x_c1|x_c0|y_c1|y_c0, which is the X1,X2,Y1,Y2 order risc0-groth16 lists them in) for the
Solana program. Reads the decimal constants from the risc0-groth16 crate source and the control ids
printed by `tessera-risc0-host vk`.
    python3 scripts/gen_vk.py <risc0-groth16 src/verifier.rs> <control_root hex> <bn254_control_id hex> > risc0_vk.rs"""
import re, sys

src = open(sys.argv[1]).read()
c = {k: int(v) for k, v in re.findall(r'const (\w+): &str =\s*"(\d+)"', src)}


def be(n):
    return n.to_bytes(32, 'big')


def arr(b):
    return '[' + ', '.join(f'0x{x:02x}' for x in b) + ']'


g1 = lambda p: be(c[p + '_X']) + be(c[p + '_Y'])
g2 = lambda p: be(c[p + '_X1']) + be(c[p + '_X2']) + be(c[p + '_Y1']) + be(c[p + '_Y2'])
print('//! RISC Zero Groth16 verifying key and control ids (risc0-groth16 3.0.5 / risc0-zkvm 3.0.3),')
print('//! big-endian EIP-197 encoding. Generated by sealed-eval-zk/scripts/gen_vk.py; do not edit.')
print(f'pub const ALPHA_G1: [u8; 64] = {arr(g1("ALPHA"))};')
for n in ('BETA', 'GAMMA', 'DELTA'):
    print(f'pub const {n}_G2: [u8; 128] = {arr(g2(n))};')
print('pub const IC: [[u8; 64]; 6] = [')
for i in range(6):
    print(f'    {arr(g1(f"IC{i}"))},')
print('];')
print(f'pub const CONTROL_ROOT: [u8; 32] = {arr(bytes.fromhex(sys.argv[2]))};')
print(f'pub const BN254_CONTROL_ID: [u8; 32] = {arr(bytes.fromhex(sys.argv[3]))};')
